-- 20번 부서의 평균 급여
SELECT AVG(SAL)
FROM NEW_EMP
WHERE DEPTNO = 20;

-- 평균보다 적은 사람 중 JOB = 'CLERK'인 사람의 급여를 평균 급여로 변경
