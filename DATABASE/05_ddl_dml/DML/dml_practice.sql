-- 새로운 테이블 하나 만들기
CREATE TABLE NEW_EMP
AS SELECT * FROM EMP;
-- 30번 부서의 평균 급여 구하기
SELECT AVG(SAL)
FROM NEW_EMP
WHERE DEPTNO = 30;
-- 이 평균보다 작은 사원의 급여 10% 인상
