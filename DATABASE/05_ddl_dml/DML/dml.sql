-- 데이터 수정을 위한 테이블 복사
CREATE TABLE DEPT_TEMP2
AS SELECT * FROM DEPT;
-- 확인
SELECT * FROM DEPT_TEMP2;

-- 데이터 수정
-- 1) 데이터 전체 수정하기
UPDATE DEPT_TEMP2
SET LOC = 'SEOUL';
-- 확인 
SELECT * FROM DEPT_TEMP2;
-- 수정한 내용을 되돌리고 싶을 떄
ROLLBACK;

-- 2) 일부분 수정 : WHERE절 활용
UPDATE DEPT_TEMP2
SET DNAME = 'DATEBASE',
    LOC   = 'SEOUL'
WHERE DEPTNO = 40;

-- EMP_TEMP테이블의 사원들중에서 급여거 2500원 이하인 사원만 추가 수당을 50으로 수정하는 코드 작성
UPDATE EMP_TEMP
SET COMM = 50
WHERE SAL <= 2500;
SELECT * FROM EMP_TEMP;

-- 서브쿼리를 사용하여 데이터 수정하기 : DEPT테이블 40번 부서의 DNAME, LOC를 가져오는 서브쿼리
UPDATE DEPT_TEMP
SET (DNAME, LOC) = (SELECT DNAME, LOC  
                    FROM DEPT
                    WHERE DEPTNO = 40)
WHERE DEPTNO = 40;
SELECT * FROM DEPT_TEMP2;

-- WHERE절에 서브쿼리 : DEPT_TEMP2 테이블의 부서 이름이 'OPERATIONS'인 지역이름을 'SEOUL'로 변경
UPDATE DEPT_TEMP2
SET LOC = 'SEOUL'
WHERE DEPTNO = (SELECT DEPTNO
                FROM DEPT_TEMP2
                WHERE DNAME = 'OPERATIONS');
SELECT * FROM DEPT_TEMP2;

-- 데이터 삭제를 위한 EMP_TEMP2 테이블 생성
CREATE TABLE EMP_TEMP2
AS SELECT * FROM EMP;
-- 확인
SELECT * FROM EMP_TEMP2;

-- 데이터 일부분만 삭제하기
DELETE EMP_TEMP2
WHERE JOB = 'MANAGER';
SELECT * FROM EMP_TEMP2;

-- 서브쿼리를 사용하여 데이터 삭제하기
-- 급여등급이 3등급인 30번 부서 사원 삭제하기
DELETE EMP_TEMP2
WHERE EMPNO IN (SELECT E.EMPNO
                FROM EMP_TEMP2 E, SALGRADE S
                WHERE E.SAL BETWEEN S.LOSAL AND S.HISAL
                AND S.GRADE = 3
                AND E.DEPTNO = 30);
SELECT * FROM EMP_TEMP2;

-- 급여가 3000이상인 사원을 삭제하는 코드
DELETE EMP_TEMP2
WHERE SAL >= 3000;

