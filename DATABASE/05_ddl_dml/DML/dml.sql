-- 날짜 데이터 입력을 위해 EMP_TEMP테이블 생성
CREATE TABLE EMP_TEMP
AS SELECT * 
   FROM EMP
   WHERE 1 <> 1; -- 테이블의 구조는 똑같지만 데이터는 복사하고 싶지 않을 때 사용 1은 1과 같지 않다 : False로 결과적으로 행은 만들어지지 않음
-- 확인
SELECT * FROM EMP_TEMP;

