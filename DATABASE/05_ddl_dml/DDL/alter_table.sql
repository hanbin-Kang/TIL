-- ==========================================================================================
-- ■ ALTER TABLE
-- ==========================================================================================


-- ==========================================================================================
-- 1. 테이블 복사
-- ==========================================================================================

-- EMP 테이블의 구조와 데이터를 복사하여 EMP_ALTER 테이블 생성

CREATE TABLE EMP_ALTER
AS
SELECT *
FROM EMP;

SELECT *
FROM EMP_ALTER;


-- ==========================================================================================
-- 2. 열 추가 - ADD
-- ==========================================================================================

-- HP 열 추가
-- 휴대폰 번호를 저장하기 위한 열

ALTER TABLE EMP_ALTER
ADD HP VARCHAR2(20);

SELECT *
FROM EMP_ALTER;


-- ==========================================================================================
-- 3. 열 이름 변경 - RENAME COLUMN
-- ==========================================================================================

-- HP 열의 이름을 TEL로 변경

ALTER TABLE EMP_ALTER
RENAME COLUMN HP TO TEL;

SELECT *
FROM EMP_ALTER;


-- ==========================================================================================
-- 4. 열의 자료형 변경 - MODIFY
-- ==========================================================================================

-- EMPNO 열의 자료형 크기를 NUMBER(4) → NUMBER(5)로 변경

ALTER TABLE EMP_ALTER
MODIFY EMPNO NUMBER(5);

DESC EMP_ALTER;


-- ==========================================================================================
-- 5. 열 삭제 - DROP COLUMN
-- ==========================================================================================

-- TEL 열 삭제

ALTER TABLE EMP_ALTER
DROP COLUMN TEL;

SELECT *
FROM EMP_ALTER;


-- ==========================================================================================
-- 6. 테이블 이름 변경 - RENAME
-- ==========================================================================================

-- EMP_ALTER → EMP_RENAME으로 테이블 이름 변경

RENAME EMP_ALTER TO EMP_RENAME;

SELECT *
FROM EMP_RENAME;


-- ==========================================================================================
-- 7. 테이블 데이터 삭제 - TRUNCATE
-- ==========================================================================================

-- 테이블의 모든 데이터를 삭제
-- 테이블 구조는 유지

TRUNCATE TABLE EMP_RENAME;


-- ==========================================================================================
-- 8. 테이블 삭제 - DROP
-- ==========================================================================================

-- 테이블 자체를 삭제
-- 데이터와 테이블 구조가 모두 삭제됨

DROP TABLE EMP_RENAME;

-- 삭제된 테이블 확인
-- → 테이블이 존재하지 않으므로 오류 발생

DESC EMP_RENAME;