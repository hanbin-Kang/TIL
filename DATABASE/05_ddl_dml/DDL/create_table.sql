-- ==========================================================================================
-- ■ CREATE TABLE
-- ==========================================================================================

-- 1. 자료형을 직접 정의하여 테이블 생성
CREATE TABLE EMP_DDL (
    EMPNO       NUMBER(4),
    ENAME       VARCHAR2(10),
    JOB         VARCHAR2(9),
    MGR         NUMBER(4),
    HIREDATE    DATE,
    SAL         NUMBER(7, 2),
    COMM        NUMBER(7, 2),
    DEPTNO      NUMBER(2)
);

-- 테이블 구조 확인
DESC EMP_DDL;


-- ==========================================================================================
-- ■ 기존 테이블의 열 구조 + 데이터 복사
-- ==========================================================================================

-- 기존 테이블과 동일한 구조의 테이블을 만들 때
-- 서브쿼리를 활용하면 편리하다.

CREATE TABLE DEPT_DDL
AS
SELECT *
FROM DEPT;

-- 테이블 구조 확인
DESC DEPT_DDL;

-- 테이블 데이터 확인
SELECT *
FROM DEPT_DDL;


-- ==========================================================================================
-- ■ 기존 테이블의 열 구조 + 일부 데이터 복사
-- ==========================================================================================

-- 기존 테이블의 구조는 유지하면서
-- 특정 조건에 해당하는 데이터만 복사하여 테이블 생성

-- EMP 테이블에서 DEPTNO가 30인 사원만 복사
CREATE TABLE EMP_DDL_30
AS
SELECT *
FROM EMP
WHERE DEPTNO = 30;

-- 테이블 데이터 확인
SELECT *
FROM EMP_DDL_30;


-- ==========================================================================================
-- ■ 기존 테이블의 열 구조만 복사
-- ==========================================================================================

-- 기존 테이블과 동일한 열 구성을 가지면서
-- 데이터가 없는 빈 테이블을 생성
--
-- WHERE절의 조건을 항상 FALSE가 되도록 작성하면
-- 조회되는 데이터가 없기 때문에 열 구조만 복사된다.

CREATE TABLE EMPDEPT_DDL
AS
SELECT E.EMPNO,
       E.ENAME,
       E.JOB,
       E.MGR,
       E.HIREDATE,
       E.SAL,
       E.COMM,
       D.DEPTNO,
       D.DNAME,
       D.LOC
FROM EMP E, DEPT D
WHERE 1 <> 1;

-- 생성된 테이블 데이터 확인
SELECT *
FROM EMPDEPT_DDL;