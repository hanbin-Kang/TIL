# ==========================================================================================      
# ■ 문제 요약
# 점수가 global 변수로 주어지고, 점수가 유효한 기준 내에 있는 점수인지, 아닌지 기준 내의 점수면 기준점보다 높은지를 판단
# ==========================================================================================      
# ■ 알고리즘
# 1. 함수를 정의하고, 점수가 유효한 점수인지 판단한다
# 2. 유효한 점수가 아니면 조기 종료, 유효한 점수일 땐 기준점수 이상인지 이하인지에 따라 반환값이 달라짐
# ==========================================================================================      

score = int(input())

# 유효한 범위 내에서 60점 이상이면 합격, 아니면 불합격
# 유효하지 않은 범위 내 점수는 판단 전에 조기 종료

# 함수 정의
def evaluate(score : int):
    '''
    Args:
        score (int): positional, 반드시 입력되어야하는 점수
    Returns:
        합격 or 불합격 or 유효하지 않은 점수 (str): 입력된 매개변수를 기준에 따라 판단하여 반환
    '''
    # 유효한 조건 외의 점수: 조기 종료
    if score > 100 or score < 0:
        return '유효하지 않음'
    # 유효한 범위 내의 점수: 기준을 따라 판단
    else:
        passing_score = 60 # 합불 기준점수
        # 합격점
        if score >= passing_score:
            return '합격'
        # 불합격점
        else:
            return '불합격'

# 함수 호출
print(evaluate(score))

# ==========================================================================================
# ■ 개선점
# 1. if score > 100 or score < 0: 이것보다 if not (0 <= score <= 100):이 더 간단 명료하다.
# 2. passing_score 변수를 만든 이유는 유지 보수 측면에서의 편의성 때문인데
#    함수 내에 두면 지역변수로 함수가 호출될때만 사용되는 변수여서 바깥에 두는편이 좋다.
# 3. if-else절에서 if절로 유효하지 않은 조건을 거르고 이미 반환을 하여 함수가 종료되기 때문에 
#    굳이 else절로 두어 if절을 중첩하지 않고, if절을 한번 더 사용하는 편이 낫다.
# ==========================================================================================
# ■ AI 추천 코드
score = int(input())

# 유효한 범위 내에서 60점 이상이면 합격, 아니면 불합격
# 유효하지 않은 범위 내 점수는 판단 전에 조기 종료

PASSING_SCORE = 60  # 모듈 상수로 분리하여 재사용성 향상

# 함수 정의
def evaluate(score: int):
    '''
    Args:
        score (int): positional, 반드시 입력되어야하는 점수
    Returns:
        '합격' | '불합격' | '유효하지 않음' (str): 입력된 매개변수를 기준에 따라 판단하여 반환
    '''
    # 유효한 조건 외의 점수: 조기 종료 (else 제거로 패턴 명확화)
    if not (0 <= score <= 100):  # Python 연속 비교로 가독성 향상
        return '유효하지 않음'

    # 유효한 범위 내의 점수: 기준을 따라 판단
    if score >= PASSING_SCORE:  # 상수 참조
        return '합격'
    return '불합격'  # else 생략 — 위에서 합격이 반환되지 않으면 불합격

# 함수 호출
print(evaluate(score))

