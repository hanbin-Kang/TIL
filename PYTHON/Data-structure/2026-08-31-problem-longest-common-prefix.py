# ==========================================================================================
# ■ 문제 요약
# 리스트 안에 단어들의 최장 공통 접두사를 구하는 문제
# ==========================================================================================
# ■ 알고리즘
# 1. 단어의 개수가 1개인 것과 2개 이상인 경우로 구분
# 2. 각 단어의 접두사를 한글자씩 늘려가며 리스트에 담음
# 3. 접두사별 등장횟수를 딕셔너리에 저장
# key - 접두사, value - 해당 접두사의 등장 횟수
# 4. 딕셔너리를 역순으로 배열 후 len(words)와 같은 value값을 가지는 key값을 출력
# 5. 공통 접두사가 없으면 '없음' 출력
# ==========================================================================================

words = input().split()

# 단어가 1개, 2개, 3개 ... 인 경우가 있어 일반화를 해야함
# 단어가 1개인 경우와 아닌경우로 나누어서 진행
if len(words) == 1:
    print(" ".join(words))

# 1개가 아닌 경우 
else:
    char_list = []
    # n번째 글자 비교 -> 같으면 추가, 다르면 정지 후 출력 
    # 인덱스 활용
    for word in words:
        for idx in range(len(word)):
            char_list.append(word[0:idx + 1])
    # 인덱싱 한것을 딕셔너리에 넣고 value 값을 구함 
    char_dict = {}
    for i in char_list:
        char_dict[i] = char_dict.get(i, 0) + 1
    # 사전식 배열을 역순으로 하고, 같은 것이 나오면 정지
    count = 0 # flag
    for key, value in sorted(char_dict.items(), reverse=True):
        if char_dict[key] == len(words):
            count += 1
            print(key) 
            break
    # 같은것이 없을 경우
    if count == 0:
        print("없음")

# ==========================================================================================
# ■ 개선점
# 모든 단어의 접두사를 리스트와 딕셔너리에 저장하는 기존 방식은 메모리 사용량이 많다.
# words[0]을 기준으로 다른 단어들과 비교하며 접두사를 줄이는 방식으로 개선할 수 있다.
# ==========================================================================================
# ■ AI 추천 코드

words = input().split()

# 단어가 1개 이상인 경우 모두 동일 로직으로 처리 가능

# 첫 단어를 초기 접두사로 설정 : flower
prefix = words[0]

# 나머지 단어들과 비교하며 접두사를 줄여나감
for word in words[1:]: # 두번째 단어부터 마지막 단어까지 : flow, flight
    # prefix가 현재 단어의 시작 부분과 일치하지 않으면 한 글자씩 제거
    # startswith : "apple".startswith("app") : True
    while not word.startswith(prefix):
        prefix = prefix[:-1]  # 마지막 글자 제거
        if not prefix:  # 접두사가 빈 문자열이 되면 공통 접두사 없음
            break

# 결과 출력
if prefix:
    print(prefix)
else:
    print("없음")