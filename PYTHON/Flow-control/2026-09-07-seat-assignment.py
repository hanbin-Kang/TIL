# =============================================================================================== 
# ■ 문제 요약
# 학생 수 N과 학생 이름을 입력받아 3행 4열(총 12자리) 좌석에 행 우선 순서로 배치하고, 빈 자리는 .으로 채워 출력하는 문제
# ===============================================================================================      
# ■ 알고리즘
# 학생들의 이름을 받아 리스트에 넣고, 비행기 좌석도 리스트에 넣는다
# 비행기 좌석 리스트와 학생 이름 리스트의 인덱스를 비교하여 있으면 이름, 없으면 '.'을 넣어 비행기 좌석 리스트를 수정한다
# 3행 4열을 기준으로 출력한다
# ===============================================================================================

n = int(input())
names = []
for _ in range(n):
    names.append(input())

# 3행 4열짜리 비행기 좌석이 존재한다. 
seat = []
for row in range(3):
    for col in range(4):
        seat.append((row, col))
# 좌석 배정
for idx in range(len(seat)):
    if idx < len(names):
        seat[idx] = names[idx]
    else:
        seat[idx] = '.'
# 출력
for i in range(3):
    start = i * 4
    end = start + 4
    print(" ".join(seat[start:end]))

# ==========================================================================================
# ■ 개선점
# 각각 좌석을 하나하나 배정하여 수정하지 말고 컴프리헨션을 사용하여 빈리스트에 이름과 '.'을 넣는다
# 출력할때도 인덱스 슬라이싱을 사용하여 더욱 간단하게 해결할 수 있다
# ==========================================================================================
# ■ AI 추천 코드

n = int(input())
names = []
for _ in range(n):
    names.append(input())

# ① 좌석 리스트 구성: 이름이 있으면 이름, 없으면 '.' 으로 바로 채움
# 튜플 초기화 단계 없이 한 번에 완성
seat = [names[i] if i < n else '.' for i in range(12)]

# ② 행별 출력
for i in range(3):
    print(" ".join(seat[i * 4:(i + 1) * 4]))  # 슬라이스로 각 행 4칸 추출