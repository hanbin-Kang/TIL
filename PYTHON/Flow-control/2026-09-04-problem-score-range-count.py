# ==========================================================================================      
# ■ 문제 요약
# 입력받은 점수들이 어느 구간에 속하고, 그 구간에 속한 점수의 개수를 구하여 출력하여라
# ==========================================================================================      
# ■ 알고리즘
# 1. 반복문을 통해 사용자가 입력한 정보를 모두 리스트에 넣는다
# 2. 입력된 점수가 3자리일때와 아닐때를 구분한다
# 2-1) 3자리일 때는 100점, 10을 딕셔너리에 추가한다
# 2-2) 3자리가 아닐때는 입력한 점수의 첫번째 자리의 숫자를 뺴서 딕셔너리에 넣는다
# 3. 딕셔너리에 입력한 점수의 1의 자리 + 그것이 나온 횟수를 적어놓는다
# 4. 출력 : 어느 구간에 속해있는지 + 나온 횟수 * '#'
# ==========================================================================================      

n = int(input())
# 리스트에 넣고 순서대로 정렬

scores_list = []
scores_dict = {}

for _ in range(n):
    score = int(input())
    scores_list.append(score)
scores_list.sort()

for s in scores_list:
    s = str(s)
    # s가 세자리수 일 때
    if len(s) == 3:
        scores_dict[s[0:2]] = scores_dict.get(s[0:2], 0) + 1
    else:
        scores_dict[s[0]] = scores_dict.get(s[0], 0) + 1

for i, j in scores_dict.items():
    first = int(i) * 10
    count = j * "#"
    if first >= 90:
        if first == 90:
            print(f"{first}~{first + 10}: {count}")
        else:
            print(f"{first - 10}~{first}: {count}")
    else:
        print(f"{first}~{first + 9}: {count}")

# ==========================================================================================
# ■ 개선점
# 구간 계산은 score // 10으로 10의 자리를 바로 구하면 훨씬 단순하고 안전하게 처리할 수 있다
# min(score // 10, 9)을 통해 80점인 사람은 min(8, 9)으로 8이고, 100점인 사람은 min(10, 9)이기에
# 훨씬 자연스러운 코드가 된다
# ==========================================================================================
# ■ AI 추천 코드

n = int(input())
# 리스트에 넣고 구간별 카운트

# 인덱스 0~9: 0~9점 / 1: 10~19점 / ... / 9: 90~100점
counts = [0] * 10

for _ in range(n):
    score = int(input())
    interval_idx = min(score // 10, 9)  # 100점은 인덱스 10이 되므로 9로 고정
    counts[interval_idx] += 1

for idx, cnt in enumerate(counts):
    if cnt == 0:
        continue  # 인원 0명 구간 제외
    bar = '#' * cnt
    # 마지막 구간(90~100)은 끝을 100으로 표기
    if idx == 9:
        label = f'90~100'
    else:
        label = f'{idx * 10}~{idx * 10 + 9}'
    print(f'{label}: {bar}')