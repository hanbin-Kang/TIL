# ==========================================================================================      
# ■ 문제 요약
# 입력 받은 점수들이 각각 어느 등급에 몇명씩있는지를 출력하는 문제
# ==========================================================================================      
# ■ 알고리즘
# 딕셔너리를 만든다 (어느 등급에 몇명이 있는지를 담기 위한 딕셔너리, 등급별 점수 구간을 담은 딕셔너리)
# min을 사용하여 10으로 나눈값과 비교하여 100점일때를 일반화한다
# 딕셔너리에 각각 등급별 몇명이 있는지 담고, 출력한다  
# ========================================================================================== 
n = int(input())

score_dict = {"A" : 0, "B" : 0, "C" : 0, "D" : 0, "F" : 0}
grade = {"A" : "(90~100)", "B" : "(80~89)",
         "C" : "(70~79)", "D" : "(60~69)", 
         "F" : "( 0~59)"}

for _ in range(n):
    score = int(input())
    value = min(score // 10, 9)
    if value >= 9:
        score_dict["A"] += 1
    elif value >= 8:
        score_dict["B"] += 1
    elif value >= 7:
        score_dict["C"] += 1
    elif value >= 6:
        score_dict["D"] += 1
    else:
        score_dict["F"] += 1

# 출력
for key, value in score_dict.items():
    print(f"{key} {grade[key]}: {value}명")

