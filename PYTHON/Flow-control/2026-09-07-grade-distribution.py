# ■ AI 추천 코드

# 방법1)
n = int(input())
# 각종 딕셔너리 생성
grade_map = {9: "A", 8: "B", 7: "C", 6: "D"} # 점수 앞자리
score_dict = {"A": 0, "B": 0, "C": 0, "D": 0, "F": 0} # 각 등급에 몇명이 오는지를 담는 딕셔너리
grade_label = {"A": "(90~100)", "B": "(80~89)", "C": "(70~79)", "D": "(60~69)", "F": "( 0~59)"} # 등급과 범위

for _ in range(n):
    score = int(input())
    # dict.get(key, default)를 사용해 6 미만은 전부 "F" 처리
    value = min(score // 10, 9)
    target_grade = grade_map.get(value, "F") # grade_map이라는 딕셔너리 안에 값이 있으면 target_grade는 그 값, 없으면(60점 미만) F
    score_dict[target_grade] += 1

for k, v in score_dict.items():
    print(f"{k} {grade_label[k]}: {v}명")

