# 방법2)
n = int(input())

grade_map = {9: "A", 8: "B", 7: "C", 6: "D"}

# [카운트, 범위] 형태로 하나의 딕셔너리에 통합
grade_info = {
    "A": [0, "(90~100)"],
    "B": [0, "(80~89)"],
    "C": [0, "(70~79)"],
    "D": [0, "(60~69)"],
    "F": [0, "( 0~59)"]
}

for _ in range(n):
    score = int(input())
    value = min(score // 10, 9)
    target_grade = grade_map.get(value, "F")
    
    # 해당 등급의 0번째 요소(카운트)를 1 증가
    grade_info[target_grade][0] += 1

# 출력할 때도 딕셔너리 하나만 돌리면 끝!
for grade, info in grade_info.items():
    count = info[0]
    label = info[1]
    print(f"{grade} {label}: {count}명")